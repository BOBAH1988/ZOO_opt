"""
Проект 14: Прайс клиенту ИП Мамедов.

ЗАДАЧА
По понедельникам, вместе с проектом 3 (Сети Ухта), отправляем клиенту
dolinamecti@mail.ru сокращённый прайс из репозитория.

ПОЧЕМУ ОТДЕЛЬНЫЙ ПРОЕКТ, А НЕ ДОБАВЛЕНИЕ В ТРЕТИЙ
У проекта 3 другой файл (scripts/price_files/Прайс Зоо Логистик сетям.xlsx),
другой список получателей из файла и другая тема. Здесь файл один и он
обновляется владельцем вручную через Upload files. Соединять их в одном
скрипте нельзя: рассылка сетям по чужой ошибке должна падать отдельно от
рассылки одному клиенту.

ПОЧЕМУ ЗАПУСКАЕТСЯ ВМЕСТЕ С ПРОЕКТОМ 3
Тот же день (понедельник), тот же повод и тот же файл-день: клиент ждёт
прайс вместе с сетями. Отдельный workflow не нужен — вызов идёт из
weekly_sety_price.yml вторым шагом, и только если первый отработал
успешно.

ВРЕМЯ ОТПРАВКИ
Проверяется, но только нижняя граница: НЕ РАНЬШЕ 07:00 МСК
(EARLIEST_SEND, требование владельца 19.10.2026 — рассылка ушла в 03:05).
Верхней границы нет по той же причине, что и у проекта 3: слот может не
дойти вообще, и клиент останется без прайса. Ручной запуск и тест проверку
времени обходят.

УВЕДОМЛЕНИЕ
Одно на оба проекта: «Прайс сетям и ИП Мамедов выслан». Его шлёт этот проект
после успешной отправки, а проект 3 в парном запуске своего уведомления не
шлёт — иначе владелец получил бы два письма об одном и том же.

ЗАЩИТА ОТ ПОВТОРНОЙ ОТПРАВКИ
Как и у проекта 3: имя файла ищется в папке «Отправленные» за сегодня.
Это спасает, если владелец отправил прайс клиенту сам, а потом отработал
задержанный слот. СВОЮ отправку проверка тоже видит — после отправки
письмо дописывается в «Отправленные» (record_sent_copy в mail_common):
сервер копию письма, ушедшего по SMTP, сам не делает, и без этой записи
второй слот дня отправил бы клиенту дубль (по 2 письма за день — случай
прошлых недель, пойман 19.10.2026). При ручном запуске вместо молчания
приходит письмо с объяснением.

Требуются переменные окружения:
    MAILRU_LOGIN, MAILRU_APP_PASSWORD, NOTIFY_EMAIL
    SKIP_IF_SENT (опционально, чекбокс «Не дублировать рассылку»)
    MANUAL_RUN (опционально, ставит workflow при ручном запуске)
"""

from pathlib import Path
from typing import ClassVar

from mail_common import (
    EARLIEST_SEND,
    is_manual_run,
    is_skip_if_sent,
    is_too_early,
    now_msk,
    resolve_recipients,
    sent_file_today,
    sent_mail_today,
)
from notify import send_notification
from project_base import RESULT_ERROR, RESULT_SUCCESS, ProjectBase
from send_email import send_file

SCRIPT_DIR = Path(__file__).resolve().parent


class MamedovProject(ProjectBase):
    """Проект: сокращённый прайс для ИП Мамедов."""

    # Файл лежит в репозитории и обновляется вручную через Upload files.
    PRICE_FILE = SCRIPT_DIR / "price_files/Сокращенный прайс.xlsx"
    # Получатели: клиент ИП Мамедов + владелец (чтобы видеть, что уходит
    # клиенту). Файл со списком не нужен: адреса редко меняются, и жёсткая
    # привязка в коде не даёт им «расползтись» правкой файла.
    RECIPIENTS: ClassVar[list[str]] = ["dolinamecti@mail.ru", "muxtar71@internet.ru"]
    # Тема та же, что у проекта 3: это тот же документ — прайс ООО
    # «ЗОО Логистик», просто адресованный одному клиенту.
    #
    # ИЗ-ЗА ЭТОГО ЗАЩИТА ОТ ДУБЛЯ ИДЁТ ПО ФАЙЛУ, А НЕ ПО ТЕМЕ
    # Темы у проектов 3 и 14 совпадают, а письма уходят разным адресатам.
    # Поиск по теме их не различает: отправив клиенту, проект 3 увидел бы
    # «своё» письмо в «Отправленных» и решил бы, что сетям уже отправлено.
    # Различает имя вложения: у сетям «Прайс Зоо Логистик сетям.xlsx», здесь
    # «Сокращенный прайс.xlsx».
    SUBJECT = 'Здравствуйте, прайс от ООО "ЗОО Логистик"'
    BODY = "Заказ принимаем до вторника 15-00, минимальный заказ 5000р. Доставка в чт."

    # Префикс темы тестовых отправок: и в ящике видно, что это тест, и
    # защита от дубля их не считает за настоящую рассылку.
    TEST_SUBJECT_PREFIX = "[ТЕСТ] "

    def __init__(self):
        super().__init__(
            key="mamedov",
            title="Прайс ИП Мамедов",
        )
        self.skip_if_sent = is_skip_if_sent()

    def process(self) -> str:
        """Отправить прайс клиенту.

        Проверяется только нижняя граница — не раньше 07:00 МСК
        (EARLIEST_SEND): ночью письмо клиенту не уходит ни при какой
        задержке. Верхней границы НЕТ намеренно: проект 3 после инцидента
        05.10.2026 отправляет в любое время, и ждать чего-то тут означало бы
        повторить ту же ошибку — слот может не дойти никогда, и клиент
        останется без прайса. Ручной запуск и тест проверку обходят.
        """
        # НЕ РАНЬШЕ 07:00 МСК — до всяких обращений к почте (дёшево и
        # надёжно). Раньше времени здесь вообще не проверялось, и 19.10.2026
        # прайс клиенту ушёл в 03:05 вместе с рассылкой сетям.
        if is_too_early():
            now = now_msk()
            self.logger.info(
                f"Сейчас {now.hour:02d}:{now.minute:02d} МСК — раньше "
                f"{EARLIEST_SEND[0]:02d}:{EARLIEST_SEND[1]:02d} плановый "
                "запуск прайс клиенту не отправляет, ждёт следующего слота")
            return RESULT_SUCCESS

        price_path = Path(self.PRICE_FILE)
        if not price_path.exists():
            self.logger.error(f"Файл прайса не найден: {price_path}")
            return RESULT_ERROR

        subject = self.SUBJECT
        # Тестовый режим проверку пропускает: тест всегда отправляет, иначе
        # пробный запуск не дал бы боевому слать по-настоящему.
        if (self.skip_if_sent and not self.test_mode
                and sent_file_today(price_path.name)):
            self.logger.info(
                f"Файл «{price_path.name}» клиенту уже отправлен сегодня — "
                "повтор пропущен")
            # Молчать нельзя только при РУЧНОМ запуске: человек нажал кнопку
            # и должен понимать, почему письма клиенту нет.
            if is_manual_run():
                send_notification(
                    "Прайс ИП Мамедов повторно не отправлен",
                    "Сегодня он уже уходил — защита от дубля пропустила "
                    "отправку. Если нужно отправить повторно, снимите "
                    "галочку «Не дублировать рассылку».",
                )
            return RESULT_SUCCESS

        try:
            if self.test_mode:
                subject = self.TEST_SUBJECT_PREFIX + self.SUBJECT
                recipients = resolve_recipients(
                    self.RECIPIENTS, True, what="прайсу ИП Мамедов")
            else:
                recipients = self.RECIPIENTS

            self.logger.info(
                f"Получателей: {len(recipients)} — {', '.join(recipients)}")
            # include_promo=False — клиенту акции не нужны, в письме должна
            # быть только подпись владельца.
            send_file(
                str(price_path),
                recipients=recipients,
                subject=subject,
                body=self.BODY,
                include_promo=False,
            )
            self.logger.info("Готово: прайс ИП Мамедов отправлен.")

            # Одно уведомление на оба проекта парного запуска.
            # ПРАВКА: проверяем, не ушло ли это уведомление сегодня уже
            # раньше. Второй слот дня (14:11) шарился в 03:57 уведомление и
            # отправил вторую копию на клиент. Без этой проверки проект 14
            # шлёт «Прайс сетям и ИП Мамедов выслан» дважды за день — и
            # клиент увидит два одинаковых письма.
            if sent_mail_today("Прайс сетям и ИП Мамедов выслан"):
                self.logger.info(
                    "Уведомление о высланном прайсе уже отправлено сегодня — "
                    "не повторяю"
                )
            else:
                send_notification(
                    "Прайс сетям и ИП Мамедов выслан",
                    f"Сетям и клиенту ИП Мамедов "
                    f"({', '.join(self.RECIPIENTS)}) отправлен файл "
                    f"«{price_path.name}».",
                )
            return RESULT_SUCCESS

        except Exception as e:
            self.logger.error(f"Ошибка при отправке: {e}")
            return RESULT_ERROR


def main() -> bool:
    return MamedovProject().run()


if __name__ == "__main__":
    raise SystemExit(0 if main() else 1)
