"""
Оркестратор сценария "Сети Ухта" (по понедельникам, разовая отправка).

В отличие от сценариев Прусакова/Ухта, здесь НЕТ ожидания входящего
письма — файл заранее лежит в репозитории, скрипт просто рассылает
его по списку адресов. Поэтому автоответчики от получателей никак
не влияют на работу.

ЗАЩИТА ОТ ДУБЛЯ (SKIP_IF_SENT, по умолчанию включена): перед отправкой
сверяется с папкой "Отправленные" — если прайс с этой темой уже уходил
сегодня (например, был отправлен вручную до планового запуска),
рассылка пропускается МОЛЧА, запись только в журнал. Раньше здесь
приходило уведомление "Прайс сетям уже отправлен", но с many слотами
(см. ниже) оно стало бы приходить десяток раз за утро. Тестовые
запуски за отправку не считаются: их тема помечается префиксом
"[ТЕСТ] ".

ОКНО ОТПРАВКИ (главное отличие от прежней версии)
Проект рассылает прайс БЕЗУСЛОВНО, поэтому один-единственный слот в
cron ничего не гарантировал: GitHub Actions исполнил слот 08:09 с
задержкой в 6,5 часа, и 28.09.2026 прайс ушёл в 14:38 вместо утра.

Сетка слотов НЕ РАБОТАЕТ как задумано. Замер 05.10.2026: из 16 cron-слотов
(02:05–09:35 МСК) GitHub выполнил два — в 04:45 и 08:25, причём с задержкой
от расписания. Оба попали в «рано» и тихо вышли, прайс не ушёл, и ждать было
нечего: следующего слота может и не быть.

Поэтому окно ОТПРАВКИ убрано, но осталось НИЖНЕЕ ограничение:
    * НЕ РАНЬШЕ 07:00 МСК (EARLIEST_SEND) — письма в три часа ночи не должно
      быть ни при какой задержке: требование владельца, 19.10.2026 (слот в
      03:05 реально уходил, рассылка приходила в 3 утра);
    * первый слот после 07:00 отправляет прайс — лучше поздно, чем не
      отправить неделю вообще;
    * позже 12:00 МСК (SEND_UNTIL) — отправка с пометкой «с опозданием» в
      уведомлении, чтобы задержка GitHub была видна;
    * ручной запуск (MANUAL_RUN) и тестовый режим отправляют всегда, в том
      числе до 07:00;
    * повторные слоты того же дня молчат по защите от дубля: она видит
      письмо в «Отправленных» благодаря record_sent_copy (сервер копию сам
      не делает — см. mail_common). Вторая рассылка шестнадцати магазинам за
      день — это хуже, чем опоздание.

SEND_FROM остался только как точка отсчёта в тексте уведомления: в какое
окно сетям полагалось прийти письмо.

После успешной отправки шлёт короткое уведомление на NOTIFY_EMAIL:
"Прайс сетям выслан".

Требуются переменные окружения:
    MAILRU_LOGIN, MAILRU_APP_PASSWORD, NOTIFY_EMAIL
    SKIP_IF_SENT (опционально, чекбокс "Не дублировать рассылку")
    MANUAL_RUN (опционально, ставит workflow при ручном запуске)
"""

from pathlib import Path

from mail_common import (
    EARLIEST_SEND,
    is_manual_run,
    is_skip_if_sent,
    is_too_early,
    now_msk,
    resolve_recipients,
    sent_file_today,
    sent_mail_today,
)
from notify import send_notification
from project_base import RESULT_ERROR, RESULT_SUCCESS, ProjectBase
from send_email import send_file

# Окно отправки по плану (МСК). Прайс должен уйти в начале рабочего дня,
# чтобы сети успели сделать заказ до вторника 15:00.
SEND_FROM = (9, 0)
SEND_UNTIL = (12, 0)

SCRIPT_DIR = Path(__file__).resolve().parent


def fmt_hm(hm: tuple[int, int]) -> str:
    return f"{hm[0]:02d}:{hm[1]:02d}"


class SetyProject(ProjectBase):
    """Проект: Прайс Сети Ухта."""

    PRICE_FILE = SCRIPT_DIR / "price_files/Прайс Зоо Логистик сетям.xlsx"
    RECIPIENTS_FILE = SCRIPT_DIR / "recipients_sety_ukhta.txt"
    SUBJECT = 'Здравствуйте, прайс от ООО "ЗОО Логистик"'
    BODY = "Заказ принимаем до вторника 15-00, минимальный заказ 5000р. Доставка в чт."

    # Префикс темы тестовых отправок: и в ящике сразу видно, что это тест,
    # и защита от дубля их не считает за настоящую рассылку.
    TEST_SUBJECT_PREFIX = "[ТЕСТ] "

    def __init__(self):
        super().__init__(
            key="sety",
            title="Прайс Сети Ухта",
        )
        self.skip_if_sent = is_skip_if_sent()

    def load_recipients(self) -> list[str]:
        """Получатели прайса сетям: список из приложения, иначе файл."""
        from mail_list import load_recipients as load_from_store

        return load_from_store("sety", self.RECIPIENTS_FILE)

    def process(self) -> str:
        """Основная логика: отправка прайса.

        Порядок проверок важен: сначала время (бесплатно, без IMAP),
        потом защита от дубля, и только потом сама рассылка.
        """
        now = now_msk()
        now_hm = (now.hour, now.minute)

        # НЕ РАНЬШЕ 07:00 МСК — ЖЁСТКОЕ ТРЕБОВАНИЕ ВЛАДЕЛЬЦА (19.10.2026).
        # Проверяется раньше остальных: это дешёвая проверка без IMAP и
        # отменить её нельзя ни задержкой GitHub, ни плотностью сетки слотов.
        # Раньше первый слот дня отправлял «в любой час» — и 19.10.2026
        # прайс сетям и ИП Мамедов ушёл в 03:05. Ручной запуск и тест
        # проверку обходят (is_too_early): нажали кнопку — отправить сейчас.
        if is_too_early():
            self.logger.info(
                f"Сейчас {fmt_hm(now_hm)} МСК — раньше "
                f"{fmt_hm(EARLIEST_SEND)} плановый запуск прайс не "
                "отправляет, ждёт следующего слота")
            return RESULT_SUCCESS

        # Ниже — уже только ПОЗДНЕЕ ограничение (см. проверку 07:00 выше):
        # оно проверяется только для плановых запусков, ручной запуск и
        # тестовый режим — это решение «отправить сейчас».
        # ОТПРАВКА НЕ ЗАВИСИТ ОТ ТОГО, В КАКОЕ ВРЕМЯ ПОПАЛ СЛОТ (кроме 07:00)
        #
        # Раньше было «рано (до 09:00) — тихий выход, ждём следующего слота».
        # На практике это означало «не отправить неделю»: GitHub из 16
        # cron-слотов выполняет ОДИН-два, и 05.10.2026 оба дошли рано утром
        # (04:45 и 08:25) — оба тихо вышли, и прайс сетям не ушёл вовсе.
        # Ждать следующего слота бессмысленно: его может не быть.
        #
        # Теперь первый слот после 07:00 отправляет в любой час. Позже 12:00 —
        # отправка с пометкой «с опозданием», чтобы по уведомлению было видно
        # задержку GitHub. Повторные слоты дня молчат по защите от дубля.
        late = False
        if not self.test_mode and not is_manual_run():
            late = now_hm >= SEND_UNTIL

        price_path = Path(self.PRICE_FILE)
        if not price_path.exists():
            self.logger.error(f"Файл прайса не найден: {price_path}")
            return RESULT_ERROR

        try:
            # ЗАЩИТА ОТ ДУБЛЯ: в тестовом режиме проверка не применяется —
            # тест всегда отправляет (иначе пробный запуск утром не дал бы
            # плановому запуску разослать прайс реально).
            #
            # Проверка работает ВСЕГДА (и при опоздании тоже): если прайс
            # уже ушёл сегодня в 09:05, задержанный слот в 14:38 не должен
            # слать его сетям второй раз. Молча, только в журнал: после
            # успешной отправки отработает ещё десяток слотов этого же дня,
            # и уведомление «уже отправлен» пришло бы пользователю десять
            # раз подряд. Письмо и так пришло одно — «Прайс сетям выслан».
            #
            # ИМЕННО ПО ИМЕНИ ФАЙЛА, А НЕ ПО ТЕМЕ
            # У проекта 14 (ИП Мамедов) тема та же — «Здравствуйте, прайс от
            # ООО "ЗОО Логистик"». Поиск по теме не различил бы их: отправив
            # клиенту, проект увидел бы «своё» письмо в «Отправленных» и
            # решил бы, что сетям уже ушло. Файлы разные: «Прайс Зоо Логистик
            # сетям.xlsx» и «Сокращенный прайс.xlsx».
            # ДВЕ НЕЗАВИСИМЫЕ ПРОВЕРКИ, а не одна
            # По имени файла — потому что тема у проектов 3 и 14 общая. Но если
            # чтение вложений в «Отправленных» не сработает (папка не та,
            # заголовок не распарсился), повтор всё равно уйдёт клиентам.
            # Тема для проекта 3 служит запасным рубежом: проект 14 в том же
            # запуске идёт ВТОРЫМ, так что к моменту проверки его письма в
            # папке ещё нет, и ложного срабатывания не будет.
            already = (sent_file_today(price_path.name)
                       or sent_mail_today(self.SUBJECT))
            if self.skip_if_sent and not self.test_mode and already:
                self.logger.info("Прайс сетям уже отправлен сегодня — рассылка пропущена")
                # РУЧНОЙ ЗАПУСК ОБРАБАТЫВАЕТСЯ ОСОБО
                # Нажали «Run workflow», а письма нет — молчать нельзя: человек
                # решит, что кнопка сломалась. Плановому запуску уведомление не
                # нужно: после рассылки отработает ещё слот, и «уже отправлено»
                # пришло бы ему дважды за день.
                if is_manual_run():
                    send_notification(
                        "Прайс сетям повторно не отправлен",
                        "Сегодня он уже уходил — защита от дубля пропустила "
                        "рассылку. Если нужно отправить повторно, снимите "
                        "галочку «Не дублировать рассылку».",
                    )
                return RESULT_SUCCESS

            recipients = self.load_recipients()
            self.logger.info(f"Получателей: {len(recipients)}")

            # В тестовом режиме прайс уходит только на NOTIFY_EMAIL
            recipients = resolve_recipients(recipients, self.test_mode, what="прайс сетям")

            subject = self.SUBJECT if not self.test_mode else self.TEST_SUBJECT_PREFIX + self.SUBJECT

            # include_promo=False — сетям акции НЕ добавляются
            send_file(
                str(price_path),
                recipients=recipients,
                subject=subject,
                body=self.BODY,
                include_promo=False,
            )
            self.logger.info("Готово: рассылка отправлена.")

            if late:
                # Опоздание видно сразу в теме письма — иначе «Прайс сетям
                # выслан» в 14:38 выглядит так же, как нормальный утренний.
                send_notification(
                    "⚠️ Прайс сетям отправлен с опозданием",
                    f"Получателей: {len(recipients)}\n"
                    f"Отправлено в {fmt_hm(now_hm)} МСК — позже планового окна "
                    f"{fmt_hm(SEND_FROM)}–{fmt_hm(SEND_UNTIL)}.\n"
                    "Причина: задержка запуска на GitHub Actions. Письмо сетям "
                    "всё же ушло, но не вовремя — стоит проверить расписание.",
                )
            else:
                # УВЕДОМЛЕНИЕ — ТОЛЬКО ПРИ РУЧНОМ ЗАПУСКЕ
                # По расписанию проект 3 идёт парой с проектом 14, и одно
                # уведомление на обоих («Прайс сетям и ИП Мамедов выслан»)
                # шлёт проект 14. Если слать и здесь, владелец получит два
                # письма об одном и том же. Ручной запуск проекта 3 в паре не
                # участвует, и без этого письма он не понял бы, что рассылка
                # ушла.
                if is_manual_run():
                    send_notification(
                        "Прайс сетям выслан", f"Получателей: {len(recipients)}")

            return RESULT_SUCCESS

        except Exception as e:
            self.logger.error(f"Ошибка при отправке: {e}")
            return RESULT_ERROR


def main() -> bool:
    project = SetyProject()
    return project.run()


if __name__ == "__main__":
    raise SystemExit(0 if main() else 1)
