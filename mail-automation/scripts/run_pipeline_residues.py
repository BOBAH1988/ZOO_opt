# Маркер последней отправки отчёта. Нужен, чтобы при повторном ручном запуске
# в тот же день не уходить вторым письмом: письмо из ящика не гасим, а защита
# от дубля живёт здесь. В GitHub Actions каждый запуск — чистая среда, маркера
# не будет, и отчёт уйдёт; при локальном повторном запуске — не уйдёт.
SENT_MARKER = PROJECT_DIR / "output" / ".sent_marker"


def already_sent_today() -> bool:
    """Был ли уже отправлен отчёт сегодня (по МСК)."""
    if not SENT_MARKER.exists():
        return False
    try:
        sent_at = SENT_MARKER.read_text(encoding="utf-8").strip()
        return sent_at == now_msk().strftime("%Y-%m-%d")
    except Exception:
        return False


def mark_sent_today() -> None:
    """Записать дату последней отправки в маркер."""
    SENT_MARKER.parent.mkdir(parents=True, exist_ok=True)
    SENT_MARKER.write_text(now_msk().strftime("%Y-%m-%d"), encoding="utf-8")


def _report_already_sent_today() -> bool:
    """Проверить по папке «Отправленные», уходил ли сегодня отчёт.

    Работает и в GitHub Actions, где маркер на диске не сохраняется.
    Проверяем по подстроке «рекомендации к заказу» (без учёта регистра),
    потому что полная тема содержит дату («Добрый день. рекомендации
    к заказу от 26.10.2026») и меняется каждый день.
    """
    imap = None
    try:
        imap = imap_connect()
        folder = find_sent_folder(imap)
        if folder is None:
            logger.warning("Папка отправленных не найдена — проверка дубля пропущена")
            return False

        status, _ = imap.select(f'"{folder}"')
        if status != "OK":
            logger.warning(f"Папку '{folder}' не удалось открыть — проверка дубля пропущена")
            return False

        today_str = _imap_date_today()
        status, data = imap.search(None, f'(SINCE "{today_str}")')
        if status != "OK" or not data or not data[0]:
            return False

        for msg_id in data[0].split():
            status, msg_data = imap.fetch(msg_id, "(BODY.PEEK[HEADER.FIELDS (SUBJECT)])")
            if status != "OK" or not msg_data or not msg_data[0]:
                continue
            raw = msg_data[0][1]
            assert isinstance(raw, (bytes, bytearray))
            msg = email.message_from_bytes(raw)
            subj = get_subject(msg).strip().lower()
            if "рекомендации к заказу" in subj:
                logger.info(f"Найден отчёт в «Отправленных» за {today_str} — повтор пропускаем")
                return True
        return False
    except Exception as e:
        logger.warning(f"Не удалось проверить папку отправленных ({e}) — считаю, что отчёта не было")
        return False
    finally:
        if imap is not None:
            imap_safe_logout(imap)


# Имя вложения с прайсом. Право 1С зовёт его одинаково в разных письмах,
# но добавлять что-то к нему нельзя: у файла может быть и префикс, и дата.
PRICELIST_MARK = "райс"


def is_pricelist_letter(letter: dict) -> bool:
    """Похоже ли письмо на выгрузку остатка.

    Слово «прайс» ищется и в теме, и в именах вложений. Тема надёжнее: у
    оператора она всегда «прайс Ухта.xls», а имя файла он может дописать как
    угодно («Ухта на 05.10.2026.xls»).
    """
    if PRICELIST_MARK in str(letter.get("subject", "")).lower():
        return True
    return any(PRICELIST_MARK in name.lower()
               for name, _ in letter.get("attachments", []))


def pick_pricelist_attachment(letter: dict) -> tuple[str, bytes] | None:
    """Вложение именно с прайсом, а не первое попавшееся.

    ЗАЧЕМ
    По теме «Ухта» подходит не только прайс. В боевом прогоне от 05.10.2026
    так было выбрано письмо «Панкова Ольга Андреевна ИП Ухта Ленина 24
    амма.xls, Панкова … титбит.xls» - это заказ клиента, а не прайс. Первое
    вложение ушло в остаток: из 2 823 позиций осталось 27, и сверка объявила
    отсутствующими ВСЕ 4 037 позиций заказа.
    """
    for name, payload in letter.get("attachments", []):
        if PRICELIST_MARK in name.lower():
            return name, payload
    # Имени с «прайс» нет, но тема про прайс — берём первое вложение:
    # оператор обычно присылает выгрузку одним файлом.
    if PRICELIST_MARK in str(letter.get("subject", "")).lower():
        attachments = letter.get("attachments", [])
        if attachments:
            return attachments[0]
    return None


def find_letter(imap, keyword: str) -> dict | None:
    """Самое свежее письмо с вложением по ключевому слову.

    Берём последнее по времени, а не первое: за выходные могли прислать
    уточнение, и сверять остаток по устаревшей версии значило бы
    рекомендовать заказ по прошлой неделе.

    Ищем среди прочитанных И непрочитанных (unseen_only=False): письмо с
    прайсом к моменту запуска обычно уже открыто тем, кто работает с почтой,
    и поиск только по непрочитанным возвращал бы пустоту.

    since_days и max_letters — обязательны именно здесь. Без них проект
    перебирал бы ВСЮ переписку с оператором и скачивал каждое письмо целиком,
    с вложениями: у оператора письма за годы, и этот перебор занимал минуты —
    запуск в GitHub висел на почте, а не на расчёте отчёта. Окно в три недели
    с запасом перекрывает и порог свежести в 6 дней, и опоздание оператора.

    Возвращает словарь из find_messages() либо None, если письма нет.
    """
    from mail_common import find_messages

    letters = find_messages(
        imap,
        SENDER_STOCK,
        subject_matcher=lambda s: subject_contains(s, keyword),
        extensions=(".xls", ".xlsx"),
        newest_first=True,
        unseen_only=False,
        since_days=LOOKBACK_DAYS,
        max_letters=MAX_LETTERS_TO_FETCH,
    )
    # Два прохода.
    #
    # Первый — только те письма, где прайс назван прямо: либо в теме, либо в
    # имени вложения. Оператор шлёт прайс с темой «прайс Ухта.xls», и письма
    # с заказами клиентов под это описание не попадают.
    #
    # Второй проход — страховка на случай, если оператор назовёт файл иначе
    # («Ухта на 05.10.xls»). Тогда берётся самое свежее письмо с любым
    # вложением, но об угадывании печатается предупреждение: молча взять не
    # то и положить заказ клиента в остаток нельзя, а молча ничего не сделать
    # — тоже нельзя, тогда неделя заказа просто пропадёт.
    for letter in letters:
        if is_pricelist_letter(letter) and pick_pricelist_attachment(letter):
            return letter

    for letter in letters:
        if letter["attachments"]:
            names = [n for n, _ in letter["attachments"]]
            logger.info(
                "ПРЕДУПРЕЖДЕНИЕ: ни в одном письме не нашлось вложения с "
                "названием «прайс». Берётся самое свежее письмо с вложениями — "
                f"«{letter['subject']}» ({', '.join(names)}). Если это не выгрузка "
                "остатка, отчёт получится пустым: попросите оператора присылать "
                "файл со словом «прайс» в названии."
            )
            return letter
    return None


def is_fresh(letter: dict) -> bool:
    """Не устарело ли письмо настолько, что отчёт будет непро текущую неделю.

    Единственная защита от повторной обработки: отметка «прочитано» здесь не
    работает, потому что письмо приходит уже прочитанным и погасить его мы не
    имеем права (оно остаётся в ящике как подтверждение, что остаток уже
    обработан).

    Без заголовка Date считаем письмо свежим: пропустить свежий прайс хуже,
    чем повторить отчёт.
    """
    sent_at = get_letter_date(letter.get("msg"))
    if sent_at is None:
        return True
    return now_msk() - sent_at <= timedelta(days=MAX_LETTER_AGE_DAYS)


# Формат Excel определяется по СОДЕРЖИМОМУ файла, а не по расширению.
#
# ZIP-контейнер (PK) — это .xlsx, и его читает openpyxl.
# OLE2-сигнатура (D0CF11E0A1B11AE1) — это старый .xls, который openpyxl
# не открывает в принципе.
#
# ПОЧЕМУ ПО СОДЕРЖИМОМУ, А НЕ ПО РАСШИРЕНИЮ
# Вложение всегда сохраняется под именем «прайс Ухта.xlsx», то есть
# расширение говорит о формате ничего. Раньше проверка стояла на
# target.suffix — она не срабатывала никогда. Настоящий .xls из письма
# сохранялся под именем .xlsx, проект падал на openpyxl с кодом 2, а
# причина терялась: в уведомление приходило «завершился с кодом 2»
# без единого слова о том, какой файл и почему не читается.
XLSX_MAGIC = b"PK\x03\x04"
XLS_MAGIC = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"


def detect_excel_format(payload: bytes) -> str:
    """Формат файла по первым байтам: "xlsx", "xls" или "unknown"."""
    if payload.startswith(XLSX_MAGIC):
        return "xlsx"
    if payload.startswith(XLS_MAGIC):
        return "xls"
    return "unknown"


def save_attachment(attachment: tuple[str, bytes], target_name: str) -> Path:
    """Записать вложение под заданным именем в папку проекта.

    Перезаписываем предыдущий файл намеренно: остаток и продажи меняются
    каждую неделю, а хранить недельные срезы в репозитории незачем.

    Имя приводится к нужному, а не берётся из письма: 1С зовёт один и тот же
    файл по-разному («Весь ассортимент за 3 мес», «Ассортимент 3 мес»), а
    проект ждёт конкретное. Отсечение по имени было бы хрупким.

    Формат при этом определяется по содержимому: оператор в любой момент
    может прислать старый .xls, и такой файл нужно либо сконвертировать,
    либо назвать прямо в ошибке — молчаливый спад с кодом 2 недопустим.
    """
    _original, payload = attachment
    kind = detect_excel_format(payload)

    if kind == "unknown":
        head = payload[:8].hex(" ") or "пусто"
        raise RuntimeError(
            f"Вложение «{_original}» не похоже ни на .xlsx, ни на .xls "
            f"(начало файла: {head}). Проект «Остатки» читает только Excel."
        )

    # Старый .xls сохраняем под своим расширением: конвертер смотрит на
    # суффикс, а сохранить .xls под именем .xlsx значило бы подсунуть
    # проекту битый файл.
    name = target_name if kind == "xlsx" else target_name.rsplit(".", 1)[0] + ".xls"
    target = PROJECT_DIR / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(payload)
    logger.info(f"Сохранено: {target} (во вложении было «{_original}», формат {kind})")

    if kind == "xls":
        target = _convert_to_xlsx(target)
    return target


def save_stock_file(letter: dict) -> Path:
    """Записать вложение с прайсом как файл остатка проекта."""
    attachment = pick_pricelist_attachment(letter)
    if attachment is None:
        raise RuntimeError(
            "В письме нет вложения с прайсом — среди файлов "
            f"{[n for n, _ in letter.get('attachments', [])]} ничего похожего "
            "на прайс. Тема письма содержит «Ухта», но это не выгрузка остатка."
        )
    return save_attachment(attachment, STOCK_FILENAME)


def _convert_to_xlsx(source: Path) -> Path:
    """Перевести старый .xls в .xlsx рядом с ним.

    Конвертер свой, scripts/xls_fonts.py: xlrd читает .xls, openpyxl пишет
    .xlsx, обе библиотеки уже стоят в requirements-residues.txt. Пакет xls2xlsx
    не используется намеренно: он тянет девять тяжёлых зависимостей (Pillow,
    fonttools, beautifulsoup4, cssutils, lxml и другие) ради HTML-режима,
    а прайс из письма приходит в .xls каждую неделю — платить минутой установки
    за еженедельную конвертацию незачем.

    Сохраняется ровно то, что нужно парсеру проекта: значения ячеек и РАЗМЕР
    ШРИФТА (11.0 — раздел, 10.0 — подраздел, 8.0 — товар). Кодировка чинится
    той же логикой, что и в convert_xls.py: файлы 1С часто без CODEPAGE, и
    xlrd тогда читает русские названия как latin-1.

    Raises:
        RuntimeError: конвертация не удалась.
    """
    from xls_fonts import convert_xls_to_xlsx

    logger.info(f"Файл в старом формате .xls — конвертируем в .xlsx ({source.name})")
    try:
        return convert_xls_to_xlsx(source, source.with_suffix(".xlsx"))
    except Exception as exc:
        raise RuntimeError(
            f"Не удалось прочитать .xls «{source.name}»: {exc}"
        ) from exc


def build_report() -> Path:
    """Запустить проект «Остатки» и вернуть путь к готовому отчёту.

    Отчёт собирается отдельным процессом, а не импортом: у проекта свои
    настройки, свои файлы и точка входа `python -m residues`. Вызов
    импортом связал бы два независимых проекта и заставил бы повторять
    его разбор аргументов.

    Raises:
        RuntimeError: проект не отработал или не создал файл.
    """
    order_out = PROJECT_DIR / "output" / "Рекомендации к заказу.xlsx"

    result = subprocess.run(
        [sys.executable, "-m", "residues", "--order"],
        cwd=str(PROJECT_DIR),
        capture_output=True,
        text=True,
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
    )
    if result.stdout:
        print(result.stdout)
    if result.returncode != 0:
        # stderr показываем в лог Actions...
        print(result.stderr, file=sys.stderr)
        # ...и обязательно вкладываем его в текст ошибки. Иначе в уведомление
        # приходит голое «завершился с кодом 2»: ни файла, ни причины. Так
        # и вышло с вложением в формате .xls — причина была видна только в
        # логе Actions, а в почту приходило бесполезное уведомление.
        detail = (result.stderr or "").strip().splitlines()
        reason = detail[-1] if detail else "проект не объяснил причину"
        raise RuntimeError(
            f"Проект «Остатки» завершился с кодом {result.returncode}: {reason}"
        )

    if not order_out.exists():
        raise RuntimeError(f"Проект отработал, но не создал файл: {order_out.name}")
    return order_out


def require_sales_report() -> Path:
    """Проверить, что отчёт о продажах за 3 месяца лежит в папке проекта.

    Файл обновляют вручную примерно раз в месяц: в отличие от остатка он не
    меняется каждую неделю, и присылать его письмом незачем. Поэтому он лежит
    в репозитории — без него workflow не сможет собрать отчёт.

    Отсутствие файла — не тихий выход, а ошибка. Раньше пайплайн ждал письма с
    продажами, не находил его и выходил молча: запуск выглядел успешным, но
    отчёт не уходил, а письмо оставалось непрочитанным. Молчание тут и было
    причиной, почему неделя заказа терялась без единого сигнала.
    """
    path = PROJECT_DIR / SALES_FILENAME
    if not path.exists():
        raise RuntimeError(
            f"Нет файла отчёта о продажах «{SALES_FILENAME}». Он лежит в "
            f"репозитории и обновляется вручную примерно раз в месяц — "
            f"загрузите свежую выгрузку: {path}"
        )
    return path


# Напоминание подгрузить новый месяц. Слова владельца, дословно: текст,
# который видит человек в письме, должен быть таким, каким его задумали.
STALE_SALES_NOTICE = "Подгрузите свежие данные за прошедший месяц."


def _report_is_stale(order_path: Path) -> bool:
    """Устарел ли отчёт о продажах — чтобы звать в тело письма напоминание.

    Ответ читается из самого отчёта: отметку проставил проект при сборке.
    Так порог и правило не расходятся между проектом и пайплайном, а дублировать
    здесь счёт дней не пришлось бы.
    """
    from openpyxl import load_workbook

    try:
        summary = load_workbook(order_path, read_only=True, data_only=True)["Сводка"]
        return any(
            "нужны свежие данные" in str(cell.value or "")
            for row in summary.iter_rows() for cell in row
        )
    except Exception as exc:
        # Напоминание не должно ломать отправку отчёта: файл только что
        # собран проектом, и если он вдруг не читается — письмо всё равно
        # уйдёт, просто без подсказки.
        logger.info(f"Не удалось проверить свежесть продаж ({exc}) — отчёт уходит без "
              "напоминания.")
        return False


def send_report(order_path: Path) -> None:
    """Отправить отчёт на почту.

    Получатель — NOTIFY_EMAIL. Когда понадобится добавить руководителя,
    достаточно дописать адрес в RESIDUES_CC: send_mail_with_attachments
    умеет копию, а менять код не придётся.

    ТЕСТОВЫЙ РЕЖИМ — ПИСЬМО УХОДИТ, НО ТОЛЬКО ВАМ
    Раньше тест не отправлял ничего и оставлял отчёт артефактом в GitHub.
    Теперь он ведёт себя как боевой запуск, но копия руководителю не
    добавляется: вы видите ровно то письмо и тот файл, которые потом уйдут
    всем, а руководитель не получает черновик. Адрес в RESIDUES_CC
    добавляют уже после того, как тест прошёл.
    """
    recipients = [get_notify_email()]
    if is_test_mode():
        cc = []
        logger.info("ТЕСТОВЫЙ РЕЖИМ: отчёт уходит только на "
              f"{get_notify_email()}, копия в RESIDUES_CC НЕ добавляется.")
    else:
        cc = [address.strip() for address in
              os.environ.get("RESIDUES_CC", "").split(",") if address.strip()]
        if cc:
            logger.info(f"Копия отчёта: {', '.join(cc)}")

    # Тема письма — приветствие и дата. Раньше было «Рекомендации к заказу за
    # 05.10.2026»: слово «за» читалось как «заказ за период», хотя речь о
    # дате, в которую составлен отчёт.
    subject = f"Добрый день. рекомендации к заказу от {now_msk().strftime('%d.%m.%Y')}"
    # Тело письма пустое — по просьбе владельца. Всё, что раньше писалось
    # текстом («во вложении рекомендации», «в файле два листа», «ни прогнозов,
    # ни денег»), повторяло содержимое вложения и только занимало экран.
    # body=None оставляет в письме одну подпись.
    #
    # ИСКЛЮЧЕНИЕ — НАПОМИНАНИЕ О ПРОДАЖАХ
    # Отчёт о продажах подгружается вручную раз в месяц, и система работает
    # по последнему файлу сколь угодно долго. Но если с конца месяца в отчёте
    # прошло больше порога, владельцу нужно напомнить про новый месяц — и
    # сделать это письмом, а не записью в логе.
    body = STALE_SALES_NOTICE if _report_is_stale(order_path) else None
    if body:
        logger.info("Отчёт о продажах устарел — в письмо добавлено напоминание.")

    send_mail_with_attachments(
        recipients,
        subject,
        [(order_path.name, order_path.read_bytes())],
        body=body,
        cc=cc or None,
    )


def main() -> None:
    # Защита от повторной отправки — только для авторассылки (schedule).
    # Ручной запуск (workflow_dispatch) должен работать всегда, даже если
    # сегодня уже уходил отчёт — иначе нельзя будет перезапустить проект
    # вручную после сбоя или при отсутствии письма.
    skip_duplicate = os.environ.get("RESIDUES_SKIP_DUPLICATE_CHECK", "false").lower() == "true"

    if not skip_duplicate:
        # Защита от повторной отправки — ПЕРЕД обращением к почте.
        # 1. Маркер на диске (работает при локальном повторном запуске).
        if already_sent_today():
            logger.info("Отчёт уже отправляли сегодня (маркер) — повторная отправка пропущена.")
            send_notification(
                "Рекомендации к заказу: дубль",
                "Это рассылка сегодня уже выполнена. Повтор не отправлен.",
            )
            return

        # 2. Проверка по папке «Отправленные» (работает и в GitHub Actions,
        #    где маркер не сохраняется между запусками — каждый run чистая среда).
        #    Проверяем по подстроке «рекомендации к заказу» (без учёта регистра),
        #    потому что полная тема содержит дату и меняется каждый день.
        if _report_already_sent_today():
            logger.info("Отчёт уже отправляли сегодня (найден в «Отправленных») — повторная отправка пропущена.")
            send_notification(
                "Рекомендации к заказу: дубль",
                "Это рассылка сегодня уже выполнена. Повтор не отправлен.",
            )
            return

    imap = imap_connect()

    # Одно входящее: остаток, то есть что физически есть на складе.
    # Отчёт о продажах НЕ приходит письмом — он лежит в репозитории и
    # обновляется вручную примерно раз в месяц. Запрашивать его письмом
    # нельзя: оператор такого письма не шлёт, и пайплайн уходил в тихий
    # выход — отчёт не уходил, письмо не гасло, запуск выглядел успешным.
    stock_letter = find_letter(imap, SUBJECT_STOCK)
    if stock_letter is None:
        imap_safe_logout(imap)
        logger.info(f"Среди писем от {SENDER_STOCK} нет прайса остатка — ничего не делаю.")
        return
    logger.info(f"Остаток: «{stock_letter['subject']}», "
          f"вложений: {len(stock_letter['attachments'])}")

    # Письмо прочитано человеком, гасить его мы не будем (и не должны), а
    # значит, повторную обработку приходится отсекать по дате. Старое письмо
    # — это уже обработанный остаток: отчёт по нему повторят в неделю, когда
    # свежего прайса так и не прислали.
    if not is_fresh(stock_letter):
        sent_at = get_letter_date(stock_letter.get("msg"))
        imap_safe_logout(imap)
        logger.info(f"Последний прайс отправлен "
              f"{sent_at:%d.%m.%Y}, старше {MAX_LETTER_AGE_DAYS} дней — "
              "считаем его уже обработанным, ничего не делаю.")
        return

    try:
        require_sales_report()
        save_stock_file(stock_letter)
        order_path = build_report()
    except Exception as exc:
        # С ящиком ничего не делаем: файл остаётся на месте для ручного
        # разбора, и следующий запуск увидит то же письмо.
        imap_safe_logout(imap)
        raise RuntimeError(f"Не удалось собрать отчёт: {exc}") from exc

    imap_safe_logout(imap)

    # Период продаж для шапки письма. Берём из отчёта 1С того же проекта
    # «Остатки»: он уже лежит на диске, а повторный разбор выгрузки ради
    # одной строки письма — лишние секунды на каждом запуске.

    # Защита от повторной отправки в тот же день: если уже уходил отчёт,
    # повторный ручной запуск не дублирует письмо.
    if not skip_duplicate and already_sent_today():
        logger.info("Отчёт уже отправляли сегодня — повторная отправка пропущена.")
        imap_safe_logout(imap)
        send_notification(
            "Рекомендации к заказу: дубль",
            "Это рассылка сегодня уже выполнена. Повтор не отправлен.",
        )
        return

    send_report(order_path)
    # Маркер ставим только в боевом режиме: в тестовом стенде scenarios.py
    # прогоняет и тестовый, и боевой сценарии подряд, и маркер из тестового
    # не должен bloqueвать боевой запуск того же прогона.
    if not is_test_mode():
        mark_sent_today()

    # Письмо НЕ гасим: оно и так приходит прочитанным, а гашение ничего бы
    # не изменило. Зато остаётся видимым в ящике как подтверждение, какой
    # остаток уже уходил в заказ. Повтор отсекает проверка свежести выше.
    send_notification(
        f"{LETTER_SUBJECT} отправлены",
        f"Обработано письмо «{stock_letter['subject']}», отчёт ушёл на "
        f"{get_notify_email()}.",
    )


if __name__ == "__main__":
    main()
